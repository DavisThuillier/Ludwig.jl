###
### Basic Graphene Model 
###

using StaticArrays

# Nearest-neighbor tight-binding parameters (energies in eV)
const hopping_energy = 2.8  
const fermi_level    = 0.1 * hopping_energy      

# Cartesian k in units of 1/a
function dispersion(k)
    structure_factor = 3 + 2 * (cos(k[1]) + cos(k[1] / 2 + sqrt(3) / 2 * k[2]) + cos(k[1] / 2 - sqrt(3) / 2 * k[2]))
    return hopping_energy * sqrt(max(0.0, structure_factor)) - fermi_level
end

function velocity(k)
    a = k[1] / 2 + sqrt(3) / 2 * k[2]
    b = k[1] / 2 - sqrt(3) / 2 * k[2]
    g = 3 + 2 * (cos(k[1]) + cos(a) + cos(b))
    g <= 0.0 && return SVector(0.0, 0.0)
    dg_dkx = -2 * sin(k[1]) - sin(a) - sin(b)
    dg_dky = sqrt(3) * (sin(b) - sin(a))
    return hopping_energy * SVector(dg_dkx, dg_dky) / (2 * sqrt(max(0.0, g)))
end

const primitives = SMatrix{2}(1.0, 0.0, 0.5, sqrt(3) / 2)

# Holohedry is 6mm (order 12): generated by a 6-fold rotation and a mirror
R = SMatrix{2}(0.5, sqrt(3) / 2, -sqrt(3) / 2, 0.5)  # C6, 60° CCW
Mx = SMatrix{2}(1.0, 0.0, 0.0, -1.0)                 # mirror across the x-axis
const generators = [R, Mx]

Weff_squared(k1, k2, k3, k4) = 1.0 # Hubbard interaction
