struct PointGroup{D,L}
    operations::Vector{SMatrix{D,D,Float64,L}}

    function PointGroup(generators::Vector{<:AbstractMatrix}, primitives::AbstractMatrix{Float64}; tol = 1e-10)
        D = size(first(generators), 1)
        static_generators = [SMatrix{D,D,Float64}(g) for g in generators] # Throws Method error if sizes are incommensurate
        for (i, generator) ∈ enumerate(static_generators)
            lattice_basis_form = primitives \ generator * primitives
            nearest_integers = round.(lattice_basis_form)
            drift = maximum(abs.(lattice_basis_form .- nearest_integers))

            drift < tol || throw(ArgumentError(
                "Generator $i does not preserve the lattice."
            ))
        end
        elements = close_group(static_generators; tol)
        return new{D,D*D}(elements)
    end
end

operations(point_group::PointGroup) = point_group.operations
order(point_group::PointGroup) = length(operations(point_group))
operation_index(operation::SMatrix{D,D,Float64}, point_group::PointGroup) where {D} = findfirst(isequal(operation), point_group.operations)

max_point_group_order(::Val{2}) = 12
max_point_group_order(::Val{3}) = 48

"""
    close_group(generators) -> Vector{SMatrix}

The full point group generated by `generators`, as its unique elements.
"""
function close_group(generators::Vector{<:SMatrix{D,D,T}}; tol = 1e-10) where {D,T}
    elements = SMatrix{D,D,Float64,D*D}[SMatrix{D,D,Float64,D*D}(I)]
    frontier = copy(elements)
    max_order = max_point_group_order(Val(D))
    while !isempty(frontier) && length(elements) <= max_order
        new_frontier = SMatrix{D,D,Float64,D*D}[]
        for g in frontier, h in generators
            candidate = g * h
            if !any(element -> isapprox(element, candidate; atol=tol), elements)
                push!(elements, candidate)
                push!(new_frontier, candidate)
            end
        end
        frontier = new_frontier
    end
    return elements
end

"""
    group_multiplication_table(ops) -> Matrix{Int}

Cayley table `mult[left, right]` = the index of `ops[left] * ops[right]` within `ops`.
"""
function group_multiplication_table(operations::Vector{<:SMatrix{D,D,Float64}}; atol = 1e-10) where {D}
    n = length(operations)
    multiplication_table = Matrix{Int}(undef, n, n)
    for left in 1:n, right in 1:n
        product = operations[left] * operations[right]
        product_index = findfirst(element -> isapprox(element, product; atol), operations)
        product_index === nothing && throw(ArgumentError("ops[$left] * ops[$right] is not a group element; ops is not closed."))
        multiplication_table[left, right] = product_index
    end
    return multiplication_table
end

group_multiplication_table(point_group::PointGroup; atol = 1e-10) = group_multiplication_table(point_group.operations; atol)

"""
    operation_permutation(i, multiplication_table)

The permutation matrix `P[i·j, j] = 1` for left multiplication by element `i` of the group whose
Cayley table is `multiplication_table`.

This is the standard regular representation, so `i ↦ P` is a homomorphism under the matrix product:
`P(i)·P(k) = P(i·k)`. The per-operation slices of `unfolding_tensor` are the transposes of these.
"""
function operation_permutation(i::Int, multiplication_table::Matrix{Int})
    permutation = zeros(Int, size(multiplication_table)...)
    for (j, k) ∈ enumerate(multiplication_table[i, :])
        permutation[k, j] = 1
    end
    return permutation
end

operation_permutation(i::Int, point_group::PointGroup) = operation_permutation(i, group_multiplication_table(point_group))

generate_permutation_matrices(multiplication_table::Matrix{Int}) =
    [operation_permutation(i, multiplication_table) for i ∈ 1:size(multiplication_table, 1)]
generate_permutation_matrices(point_group::PointGroup) = generate_permutation_matrices(group_multiplication_table(point_group))


function inverse_index(g::Int, multiplication_table::Matrix{Int})
    inverse = findfirst(isequal(1), @view multiplication_table[g, :])
    inverse === nothing && throw(ArgumentError("operation $g has no inverse in multiplication_table"))
    return inverse
end

function inverse_table(multiplication_table::Matrix{Int})
    return [inverse_index(g, multiplication_table) for g in 1:size(multiplication_table, 1)]
end

inverse_table(point_group::PointGroup) = inverse_table(group_multiplication_table(point_group))

"""
    conjugacy_classes(multiplication_table[, inverses]) -> Vector{Vector{Int}}

The conjugacy classes `{g a g⁻¹ : g ∈ G}` of the group described by a Cayley table, each as
sorted element indices. The classes partition `1:n`.

The identity is element 1 of a Cayley table and is conjugate only to itself, so `classes[1] == [1]`
always: the identity's class is index 1, not merely the first discovered. Callers may index it
directly rather than searching for it.

Pass `inverses` to reuse an `inverse_table` already at hand.
"""
conjugacy_classes(multiplication_table::Matrix{Int}) =
    conjugacy_classes(multiplication_table, inverse_table(multiplication_table))

function conjugacy_classes(multiplication_table::Matrix{Int}, inverses::Vector{Int})
    n = LinearAlgebra.checksquare(multiplication_table)
    classes = Vector{Int}[]
    assigned = falses(n)
    for a in 1:n
        assigned[a] && continue # Class already assigned
        class = sort!(unique(multiplication_table[multiplication_table[g, a], inverses[g]] for g in 1:n))
        assigned[class] .= true # Mark as assigned to a class
        push!(classes, class)
    end
    return classes
end

conjugacy_classes(point_group::PointGroup) = conjugacy_classes(group_multiplication_table(point_group))

is_integer(x; atol = 1e-10) = abs(x - round(x)) < atol

###
### Operation classification
###

# The trace fixes the rotation angle — `2cos θ` in the plane, `1 + 2cos θ` for a proper rotation in
# space and `-1 + 2cos θ` for an improper one — and a crystallographic angle is a multiple of 60° or
# 90°, so determinant and trace name an operation outright. Multiplicative order cannot: S₃ and S₆
# both cube to a reflection and so share the order 6.
function planar_rotation_order(trace::Int)
    trace == 2 && return 1
    trace == 1 && return 6
    trace == 0 && return 4
    trace == -1 && return 3
    trace == -2 && return 2
    return nothing
end

function spatial_rotation_order(trace::Int)
    trace == 3 && return 1
    trace == 2 && return 6
    trace == 1 && return 4
    trace == 0 && return 3
    trace == -1 && return 2
    return nothing
end

function spatial_rotoreflection_order(trace::Int)
    trace == 1 && return 1
    trace == 0 && return 6
    trace == -1 && return 4
    trace == -2 && return 3
    trace == -3 && return 2
    return nothing
end

"""
    operation_kind(operation) -> (Bool, Int)

Whether a crystallographic point-group `operation` is proper, and the `n` of the `Cₙ` or `Sₙ` it turns
by. A reflection is `S₁` and inversion is `S₂`.
"""
function operation_kind(operation::AbstractMatrix; atol = 1e-8)
    D = LinearAlgebra.checksquare(operation)
    (D == 2 || D == 3) || throw(ArgumentError(
        "point-group operations are classified in 2 or 3 dimensions, not $D"))
    trace = tr(operation)
    is_integer(trace; atol) || throw(ArgumentError(
        "an operation of trace $trace is not crystallographic"))
    rounded = round(Int, trace)
    proper = det(operation) > 0
    n = if D == 2
        proper ? planar_rotation_order(rounded) : 1
    else
        proper ? spatial_rotation_order(rounded) : spatial_rotoreflection_order(rounded)
    end
    n === nothing && throw(ArgumentError(
        "no crystallographic operation has determinant $(det(operation)) and trace $rounded"))
    return proper, n
end

"""
    operation_symbol(operation) -> String

Schoenflies symbol of a crystallographic point-group `operation`: `"E"`, `"C2"`…`"C6"`, `"i"`, `"σ"`,
or `"S3"`…`"S6"`.
"""
function operation_symbol(operation::AbstractMatrix; atol = 1e-8)
    proper, n = operation_kind(operation; atol)
    proper && return n == 1 ? "E" : "C$n"
    n == 1 && return "σ"
    n == 2 && return "i"
    return "S$n"
end

"""
    operation_symbols(point_group) -> Vector{String}

Schoenflies symbol of every operation of `point_group`, in stored order.
"""
operation_symbols(point_group::PointGroup; atol = 1e-8) =
    [operation_symbol(g; atol) for g in operations(point_group)]

# ±axis describe one axis, so the sign is pinned by the leading nonzero component. Adding zero
# collapses a `-0.0` produced by the arithmetic: `isequal(-0.0, 0.0)` is false, so a signed zero would
# leave `unique` holding two copies of a single axis.
function canonical_direction(axis::SVector{D,Float64}, atol) where {D}
    magnitude = norm(axis)
    magnitude < atol && return nothing
    direction = axis / magnitude
    leading = findfirst(x -> abs(x) > atol, direction)
    leading === nothing && return nothing
    return (direction[leading] < 0 ? -direction : direction) .+ 0.0
end

# The eigenvector of `matrix` for the eigenvalue whose rank-1 projector is `matrix`; the heaviest
# column spans it.
function projector_direction(projector::SMatrix{D,D,Float64}, atol) where {D}
    column = argmax(j -> sum(abs2, projector[:, j]), 1:D)
    return canonical_direction(projector[:, column], atol)
end

"""
    operation_axis(operation) -> Union{SVector,Nothing}

Unit vector along the axis a point-group `operation` distinguishes: the rotation axis of a proper
rotation, the plane normal of a reflection, or the axis of a rotoreflection. `nothing` for the
identity and for inversion, which single out no direction. In the plane only reflections have an
axis — their line normal — since a planar rotation turns about the out-of-plane direction.

The sign is canonical: the leading nonzero component is positive.
"""
function operation_axis(operation::SMatrix{2,2,Float64}; atol = 1e-8)
    det(operation) > 0 && return nothing
    return projector_direction((SMatrix{2,2,Float64}(I) - operation) / 2, atol)
end

function operation_axis(operation::SMatrix{3,3,Float64}; atol = 1e-8)
    # `-σ_n = C2(n)` and `-i = E`, so negating an improper operation exposes its axis as a rotation
    # axis and leaves the plane normal of a reflection.
    rotation = det(operation) > 0 ? operation : -operation
    isapprox(rotation, SMatrix{3,3,Float64}(I); atol) && return nothing
    turn = SVector{3,Float64}(rotation[3, 2] - rotation[2, 3],
                              rotation[1, 3] - rotation[3, 1],
                              rotation[2, 1] - rotation[1, 2])
    # A half turn has no antisymmetric part; `(C2 + I)/2` projects onto its axis instead.
    norm(turn) < atol && return projector_direction((rotation + SMatrix{3,3,Float64}(I)) / 2, atol)
    return canonical_direction(turn, atol)
end

"""
    class_symbol(class, operations) -> String

Schoenflies symbol of a conjugacy `class` of `operations`, carrying its size when it holds more than
one operation — `"E"`, `"2C4"`, `"3σ"`, `"8S6"`.
"""
function class_symbol(class::AbstractVector{Int}, operations::AbstractVector)
    symbol = operation_symbol(operations[first(class)])
    return length(class) == 1 ? symbol : "$(length(class))$symbol"
end

class_symbols(point_group::PointGroup) =
    [class_symbol(class, operations(point_group)) for class in conjugacy_classes(point_group)]
